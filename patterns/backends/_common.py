# Operators that read a phrase list from a file next to the rules. No backend
# that converts a rule to a single pattern can carry a file with it.
UNSUPPORTED_FILE_OPERATORS = ("@pmFromFile",)


def provenance_header(crs_ref: str, title: str) -> str:
    """
    The attribution block at the top of every generated file.

    Records that the output is a derived/converted work of the OWASP Core Rule
    Set (Apache-2.0). See THIRD_PARTY_NOTICES.md.

    Args:
        crs_ref: The upstream tag the rules were read from.
        title: How the target is named, such as "Nginx".
    """
    return (
        f"# Generated by fabriziosalmi/patterns from OWASP CoreRuleSet ({crs_ref}), "
        f"Apache-2.0; converted to {title}.\n"
        "# Source rules: https://github.com/coreruleset/coreruleset\n"
        "# Derived/converted work redistributed under Apache-2.0. "
        "See THIRD_PARTY_NOTICES.md.\n"
        "#\n"
    )


_TOML_ESCAPES = {"\\": "\\\\", '"': '\\"', "\b": "\\b", "\t": "\\t", "\n": "\\n",
                 "\f": "\\f", "\r": "\\r"}


def toml_string(value: str) -> str:
    """
    Writes a string as TOML, so that a parser reads back exactly `value`.

    A regular expression is full of backslashes, and in a TOML basic string
    (`"..."`) a backslash starts an escape: `"^\\$"` is not valid TOML, and Traefik
    refuses the file before it reaches a middleware (#69). A literal string
    (`'...'`) takes every character as it is, so that is used when it can be: it
    cannot hold a single quote or a control character, and then the string is
    written as a basic one with those escaped.
    """
    if "'" not in value and not any(ord(c) < 0x20 or ord(c) == 0x7F for c in value):
        return f"'{value}'"
    out = []
    for c in value:
        if c in _TOML_ESCAPES:
            out.append(_TOML_ESCAPES[c])
        elif ord(c) < 0x20 or ord(c) == 0x7F:
            out.append("\\u%04X" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def without_handled_syntax(argument: str) -> str:
    """
    What a regular expression is once the syntax a backend handles another way
    is taken out: `(?i)`, which it replaces with a case-insensitive match, and
    `(?:`, which it writes as `(`. Neither changes what the expression matches,
    so a backend that writes anything else has rewritten it.
    """
    return argument.replace("(?i)", "").replace("(?:", "(").strip()


@lru_cache(maxsize=256)
def validate_regex(pattern: str) -> bool:
    """Reports whether Python's `re` compiles the pattern."""
    try:
        re.compile(pattern)
        return True
    except re.error as e:
        logger.warning(f"Invalid regex: {pattern} - {e}")
        return False


def operator_of(rule: dict) -> dict:
    """
    The operator of a rule as the IR spells it: name, negated, argument.

    A rule from a document that predates the IR has none, and gets it read out of
    `pattern` (`@rx foo`, `!@pm a b`, or a bare expression, which is `@rx`).
    """
    operator = rule.get("operator")
    if operator is not None:
        return operator
    text = rule.get("pattern", "").strip()
    negated = text.startswith("!")
    body = text[1:] if negated else text
    if body.startswith("@"):
        name, _, argument = body[1:].partition(" ")
        return {"name": name, "negated": negated, "argument": argument.strip()}
    return {"name": "rx", "negated": negated, "argument": body}
